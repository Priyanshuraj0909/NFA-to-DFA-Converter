/**
 * Generates docs/TEST_CASES.md — a table of expected vs actual results for
 * every preset test case, produced by actually running the simulator core.
 * Run with:  node tests/generate-test-report.js
 */
'use strict';
const fs = require('fs');
const path = require('path');
const A = require(path.join(__dirname, '..', 'js', 'automata.js'));
const PRESETS = require(path.join(__dirname, '..', 'js', 'presets.js'));

const yn = (b) => (b ? 'Accept' : 'Reject');
let md = '# Test Cases — Expected vs Generated Results\n\n';
md += '_This file is generated by `node tests/generate-test-report.js` from real runs of `js/automata.js`. Do not edit by hand._\n\n';
md += 'For every test, **Expected** is the answer derived by hand from the language definition; **NFA**, **DFA** and **Min-DFA** are the answers the simulator computed. A test passes when all four agree.\n\n';

let total = 0;
let passed = 0;
const summary = [];

for (const p of PRESETS) {
  const { nfa } = A.buildNFA(p.definition);
  const conv = A.subsetConstruction(nfa);
  const min = A.minimizeDFA(conv.dfa);
  const eq = A.exactEquivalence(nfa, conv.dfa);
  const ex = A.exhaustiveCheck(nfa, conv.dfa, 8);
  md += `## ${p.name}\n\n${p.description}\n\n`;
  md += `- NFA: |Q| = ${nfa.states.length}, Σ = {${nfa.alphabet.join(', ')}}, ε-moves: ${nfa.hasEpsilon ? 'yes' : 'no'}\n`;
  md += `- Generated DFA: **${conv.dfa.states.length} states** (expected ${p.expectedDfaStates}), minimal DFA: ${min.dfa.states.length} states\n`;
  md += `- Exact equivalence L(NFA) = L(DFA): **${eq.equivalent ? 'proved' : 'FAILED'}** (${eq.pairs} state pairs)\n`;
  md += `- Exhaustive check: ${ex.checked} strings of length ≤ 8, **${ex.mismatches.length} mismatches**\n\n`;
  md += '| # | Input | Expected | NFA | DFA | Min-DFA | DFA path | Result |\n|---|---|---|---|---|---|---|---|\n';
  p.tests.forEach(([input, expected], i) => {
    const { symbols } = A.tokenize(nfa.alphabet, input);
    const n = A.simulateNFA(nfa, symbols).accepted;
    const d = A.simulateDFA(conv.dfa, symbols);
    const m = A.simulateDFA(min.dfa, symbols).accepted;
    const ok = n === expected && d.accepted === expected && m === expected;
    total++;
    if (ok) passed++;
    const pathStr = d.trace.map((t) => (t.state === null ? '∅' : t.state)).join(' → ');
    md += `| ${i + 1} | \`${input === '' ? 'ε' : input}\` | ${yn(expected)} | ${yn(n)} | ${yn(d.accepted)} | ${yn(m)} | ${pathStr} | ${ok ? '✅ PASS' : '❌ FAIL'} |\n`;
  });
  md += '\n';
  summary.push(`| ${p.name.replace(/\|/g, '\\|')} | ${nfa.states.length} | ${conv.dfa.states.length} | ${min.dfa.states.length} | ${p.tests.length} | ${eq.equivalent ? '✅' : '❌'} |`);
}

const head = `## Summary\n\n**${passed} / ${total} test cases passed.**\n\n| Example | NFA states | DFA states | Min-DFA states | Tests | L(NFA)=L(DFA) |\n|---|---|---|---|---|---|\n${summary.join('\n')}\n\n`;
md = md.replace('\n## ', '\n' + head + '## ');
md += '## Edge cases covered by the automated suite (`node tests/run-tests.js`)\n\n';
md += [
  'Empty definition (no Q, Σ, q₀) is rejected with clear errors',
  'Unknown start state, unknown symbol and unknown target state are each reported',
  'ε cannot be declared as an input symbol',
  'F = ∅ → warning, and the DFA has no accepting state (L = ∅)',
  'Unreachable NFA states are reported and never appear in the DFA',
  'Start state is final → the empty string ε is accepted',
  'NFA with no transitions → dead state ∅ is created (or omitted when the option is off)',
  'ε aliases `eps`, `λ` are recognised',
  'ε-cycles terminate (ε-closure uses a visited set)',
  'Input containing a symbol outside Σ is rejected before simulation',
  'Multi-character symbols (tokens separated by spaces)',
  'A deliberately wrong DFA is caught by the equivalence checker with the shortest counterexample',
  'State-limit guard stops an exponential blow-up gracefully',
  '300 random ε-NFAs: generated DFA equals an independent backtracking NFA simulator on 4,500 random strings',
].map((s) => `- ${s}`).join('\n') + '\n';

const out = path.join(__dirname, '..', 'docs', 'TEST_CASES.md');
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, md);
console.log(`Wrote ${out} — ${passed}/${total} passed`);
